    #[test]
    fn emit_hybrid_workspace_writes_buildable_layout() {
        // File-layout assertions only (no cargo build — that's the cc+cargo-gated
        // integration test in the xpile crate).
        let mut modules = vec![
            module(
                "app",
                SourceLang::Python,
                vec![boundary(SourceLang::Python, SourceLang::C, "square_sum")],
            ),
            c_fn("square_sum", vec![("x", Type::I64)], Type::I64),
        ];
        resolve_boundary_to_langs(&mut modules);
        let manifest = FfiManifest::reconcile(&modules).expect("reconciles");

        let dir = std::env::temp_dir().join(format!("xpile_ws_unit_{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        manifest
            .emit_hybrid_workspace(
                &modules,
                &[(
                    "_core.c".to_string(),
                    "int square_sum(int x){return x*x;}\n".to_string(),
                )],
                "pub fn main() {}\n",
                &dir,
            )
            .expect("emits workspace");

        assert!(dir.join("Cargo.toml").exists());
        assert!(dir.join("build.rs").exists());
        assert_eq!(
            std::fs::read_to_string(dir.join("csrc/_core.c")).unwrap(),
            "int square_sum(int x){return x*x;}\n"
        );
        let main_rs = std::fs::read_to_string(dir.join("src/main.rs")).unwrap();
        assert!(main_rs.contains("pub fn main()") && main_rs.contains("mod ffi_shims;"));
        let shims = std::fs::read_to_string(dir.join("src/ffi_shims.rs")).unwrap();
        assert!(shims.contains("pub fn square_sum_shim") && shims.contains("unsafe extern \"C\""));
        let _ = std::fs::remove_dir_all(&dir);
    }

